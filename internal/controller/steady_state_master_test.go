// --- what happens when the API server does not cooperate ---
//
// Every branch below is the check running against a failing API server. The rule
// they share: missing information is never read as "nothing to do". A demotion is a
// REPLICAOF, so acting on a half-read cluster is the one outcome worse than not
// acting at all -- but silently reporting success is the other, because then no
// later pass looks again.

// failPodList makes every Pod List fail, the way a torn-down informer or an
// unavailable API server does. Reads of other kinds still work.
func failPodList(err error) interceptor.Funcs {
	return interceptor.Funcs{
		List: func(ctx context.Context, c client.WithWatch, list client.ObjectList,
			opts ...client.ListOption) error {
			if _, ok := list.(*corev1.PodList); ok {
				return err
			}
			return c.List(ctx, list, opts...)
		},
	}
}

// The pod List is how the check learns how many masters there are. An empty result
// and a failed read look the same to a caller that ignores the error, and the empty
// result is the no-op path -- so a swallowed failure would turn every API outage
// into "no split brain here" forever.
func TestSteadyStateSplitBrain_ListFailureFailsThePass(t *testing.T) {
	v := steadyStateFixture(2, 1)
	r, c := newInterceptedReconciler(
		failPodList(apierrors.NewServiceUnavailable("etcd leader changed")),
		v, masterLabeledPod(v, 0, common.RoleMaster), masterLabeledPod(v, 1, common.RoleMaster))
	checker := newRolesChecker(allMasters("test-0", "test-1"))
	r.InstanceChecker = checker
	rec := &fakeEventRecorder{}
	r.Recorder = rec
	var dialed []string
	wireDemotionTarget(t, r, &dialed)

	result, done, err := r.checkSteadyStateSplitBrain(context.Background(), crGet(t, c, "test"))

	require.Error(t, err, "an unreadable cluster must not pass as a healthy one")
	assert.Contains(t, err.Error(), "listing master-labeled pods")
	assert.Contains(t, err.Error(), "etcd leader changed", "the cause must survive the wrapping")
	assert.True(t, done, "the caller returns the error, so the rest of the pass must not run")
	assert.Zero(t, result.RequeueAfter, "the rate limiter owns the retry, not a fixed delay")
	assert.Empty(t, dialed, "nothing is demoted on the strength of a failed read")
	assert.Equal(t, 0, checker.probes)
	assert.Equal(t, podHost("test", 1), knownMaster(t, c), "the recorded authority is untouched")
}

