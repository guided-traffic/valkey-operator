// --- one labeled master that the annotation does not name ---
//
// On SIGTERM of a master pod the sidecar promotes a replica (internal/sidecar/drain.go).
// The annotation keeps naming the drained pod, so the recorded authority points at
// the pod that does NOT hold the writes of the drain window.

// drainPromotedObjects builds exactly what the sidecar leaves behind in a
// three-replica cluster: the annotation still names pod-0, pod-0 carries the
// draining label the sidecar patched before failing over, pod-1 is the only pod
// labeled master, and pod-2 is the replica the drain handler repointed at pod-1.
func drainPromotedObjects() (*vkov1.Valkey, *corev1.Pod, []client.Object) {
	v := steadyStateFixture(3, 0)
	promoted := masterLabeledPod(v, 1, common.RoleMaster)
	return v, promoted, []client.Object{
		v,
		masterLabeledPod(v, 0, common.RoleDraining),
		promoted,
		masterLabeledPod(v, 2, common.RoleReplica),
	}
}

// Row 5. The stamp is positive evidence of a promotion nobody recorded, so the
// operator adopts the pod holding the drain-window writes -- and spends the
// evidence while doing it.
func TestSteadyStateSplitBrain_AdoptsTheDrainStampedMaster(t *testing.T) {
	_, promoted, objs := drainPromotedObjects()
	drainStamped(promoted)
	r, c, v := wire(t, objs...)
	checker := newRolesChecker(allMasters("test-1"))
	r.InstanceChecker = checker
	rec := &fakeEventRecorder{}
	r.Recorder = rec
	var dialed []string
	wireDemotionTarget(t, r, &dialed)

	result, done, err := r.checkSteadyStateSplitBrain(context.Background(), v)

	require.NoError(t, err)
	assert.False(t, done, "adoption moves no replication state, so the pass continues")
	assert.Zero(t, result.RequeueAfter)
	assert.Empty(t, dialed, "adoption is a record, never a REPLICAOF")
	assert.Equal(t, 1, checker.probes, "only the pod whose label contradicts the annotation is probed")

	assert.Equal(t, podHost("test", 1), knownMaster(t, c),
		"the pod holding every write of the drain window must become the recorded authority")
	assert.Empty(t, podStamp(t, c, "test-1"),
		"a recorded promotion spends the stamp, or a later pass adopts on it again")

	cm := &corev1.ConfigMap{}
	require.NoError(t, c.Get(context.Background(), types.NamespacedName{
		Name: builder.ReplicaConfigMapName(v), Namespace: testNamespace}, cm))
	assert.Contains(t, cm.Data[builder.ValkeyConfigKey], "replicaof "+podHost("test", 1),
		"the returning pod-0 reads the mounted ConfigMap, so it has to move with the annotation")

	adopted := rec.withReason("MasterAdopted")
	require.Len(t, adopted, 1, "a promotion the operator did not perform has to be visible on the CR")
	assert.Equal(t, corev1.EventTypeNormal, adopted[0].eventType)
	assert.Contains(t, adopted[0].note, "test-1")
	assert.Contains(t, adopted[0].note, "test-0")
	assert.Contains(t, adopted[0].note, "stamped")
}

// Row 6, and the whole operator-upgrade window: an old sidecar writes no stamp, so
// the structural rule has to carry the adoption on its own. test-1 has ordinal 1 and
// the replica ConfigMap names test-0, so neither path the init script offers could
// have given test-1 the master role -- somebody promoted it.
//
// This is also attack A1b, the accepted residual: a pod whose sandbox is recreated
// within kubelet's ConfigMap refresh window (~1 min) can self-claim off a mount the
// operator has already replaced, and would be adopted here. Closing it needs the
// init container's finish time against a publish timestamp; the window is bounded
// and needs the real master to be unlabeled at the same instant.
func TestSteadyStateSplitBrain_AdoptsAMasterThatCannotHaveSelfElected(t *testing.T) {
	v, _, objs := drainPromotedObjects()
	r, c, v := wire(t, append(objs, replicaConfigMapNaming(v, 0))...)
	r.InstanceChecker = newRolesChecker(allMasters("test-1"))
	rec := &fakeEventRecorder{}
	r.Recorder = rec

	_, done, err := r.checkSteadyStateSplitBrain(context.Background(), v)

	require.NoError(t, err)
	assert.False(t, done)
	assert.Equal(t, podHost("test", 1), knownMaster(t, c))

	adopted := rec.withReason("MasterAdopted")
	require.Len(t, adopted, 1)
	assert.Contains(t, adopted[0].note, "cannot have given itself the master role")
}

// [REGRESSION] The drain the structural rule cannot see, caught one state earlier
// than the split brain it used to produce.
//
// buildReplicaAddrs walks the ordinals ascending and findSyncedReplica takes the first synced peer,
// so draining a non-pod-0 master promotes pod-0 -- and pod-0 is the one pod couldNotHaveSelfElected
// can never exonerate. With the stamp lost (an old sidecar mid-upgrade, or a rejected patch) the
// operator had no evidence at all and refused, which is worse than it sounds: the annotation and
// the replica ConfigMap keep naming the drained pod, so that pod self-claims off its own mount when
// it returns (docs/adr/0008-known-master-annotation-is-the-recorded-authority.md, D8, D9), and the
// refusal has manufactured a two-master state whose only remaining resolution is another refusal.
//
// The recorded pod's own answer breaks it: test-1 came back, found test-0 serving as
// master and joined it as a replica, so whatever it held it has already given up.
// Adopting test-0 republishes the ConfigMap while test-1 is a replica, so the next
// restart keeps it one.
//
// The evidence is deliberately NOT that test-1 is the newer Pod object, which is also
// true here. TestSteadyStateSplitBrain_DoesNotAdoptASelfElectedPeerWhileTheRecordedMasterIsBooting
// is the same object shape with the opposite correct outcome, which is exactly why
// the creation order may not decide an adoption.
func TestSteadyStateSplitBrain_AdoptsTheMasterTheRecordedPodYieldedTo(t *testing.T) {
	v := steadyStateFixture(2, 1)
	r, c, v := wire(t, v,
		createdAt(masterLabeledPod(v, 0, common.RoleMaster), time.Hour),
		createdAt(masterLabeledPod(v, 1, common.RoleReplica), time.Minute),
		replicaConfigMapNaming(v, 1),
	)
	r.InstanceChecker = newRolesChecker(map[string]string{
		"test-0": common.RoleMaster,
		"test-1": common.RoleReplica,
	})
	rec := &fakeEventRecorder{}
	r.Recorder = rec
	var dialed []string
	wireDemotionTarget(t, r, &dialed)

	_, done, err := r.checkSteadyStateSplitBrain(context.Background(), v)

	require.NoError(t, err)
	assert.False(t, done)
	assert.Empty(t, dialed, "adoption is a record, never a REPLICAOF")
	assert.Equal(t, podHost("test", 0), knownMaster(t, c),
		"the pod that held the master role through the drain window has to become the record")
	assert.Empty(t, rec.withReason("MasterAdoptionRefused"))

	adopted := rec.withReason("MasterAdopted")
	require.Len(t, adopted, 1)
	assert.Contains(t, adopted[0].note, "no longer reports the master role")

	cm := &corev1.ConfigMap{}
	require.NoError(t, c.Get(context.Background(), types.NamespacedName{
		Name: builder.ReplicaConfigMapName(v), Namespace: testNamespace}, cm))
	assert.Contains(t, cm.Data[builder.ValkeyConfigKey], "replicaof "+podHost("test", 0),
		"republishing is what keeps the returning pod from self-claiming off its own mount")
}

// [REGRESSION] The adoption branch used to accept "the recorded pod is the younger
// Pod object" as evidence of a promotion, and that reading destroys the newer
// dataset. No drain occurs anywhere in this path:
//
//   - test-1 is the recorded master and its node hard-fails. No SIGTERM, so the
//     drain handler never runs, nothing is promoted and no stamp is written. The pod
//     is rescheduled and comes back as a strictly newer Pod object, still booting.
//   - test-0's node reboots in the same window. Its init container re-runs, reaches
//     no peer, takes the ordinal fallback and elects itself master. An in-place
//     sandbox recreation leaves the Pod object -- and its creationTimestamp -- alone.
//
// test-0 is then the sole labeled master and test-1 is merely newer, which is
// indistinguishable from a drain by creation order alone. Adopting republished the
// replica ConfigMap toward test-0, and test-1 full-resynced its own newer dataset
// away as soon as it finished booting: silently, and caused by the operator.
//
// The record stays put while the pod it names cannot answer for itself.
func TestSteadyStateSplitBrain_DoesNotAdoptASelfElectedPeerWhileTheRecordedMasterIsBooting(t *testing.T) {
	v := steadyStateFixture(2, 1)
	r, c, v := wire(t, v,
		createdAt(masterLabeledPod(v, 0, common.RoleMaster), 30*24*time.Hour),
		createdAt(masterLabeledPod(v, 1, common.RoleReplica), time.Minute),
		replicaConfigMapNaming(v, 1),
	)
	// test-1 is still booting: it answers nothing.
	r.InstanceChecker = newRolesChecker(allMasters("test-0"))
	rec := &fakeEventRecorder{}
	r.Recorder = rec

	_, done, err := r.checkSteadyStateSplitBrain(context.Background(), v)

	require.NoError(t, err)
	assert.False(t, done)
	assert.Equal(t, podHost("test", 1), knownMaster(t, c),
		"a pod that cannot answer may still hold the newer dataset, so the record stays on it")
	assert.Empty(t, rec.withReason("MasterAdopted"))
	require.Len(t, rec.withReason("MasterAdoptionRefused"), 1)

	cm := &corev1.ConfigMap{}
	require.NoError(t, c.Get(context.Background(), types.NamespacedName{
		Name: builder.ReplicaConfigMapName(v), Namespace: testNamespace}, cm))
	assert.Contains(t, cm.Data[builder.ValkeyConfigKey], "replicaof "+podHost("test", 1),
		"republishing toward test-0 is the write that makes the returning master discard its data")
}

