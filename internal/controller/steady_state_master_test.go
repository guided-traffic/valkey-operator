// The tests in this file pin ADR 0011 D1: once the rolling-update state annotation is
// cleared, nothing else re-detects a second master, and the -rw Service routes
// writes to every pod the sidecar labels master. The steady-state check closes
// that gap -- but a demotion is a REPLICAOF, which discards a dataset, so it never
// acts on the known-master annotation alone. The annotation is unreliable in
// exactly one way: the sidecar drain handler promotes a replica on SIGTERM and has
// no CR access to record it.
//
// Three pieces of evidence separate that promotion from a pod that gave itself the
// role, and every row below is one cell of the decision table they produce:
//
//   - the drain stamp (common.AnnotationDrainPromotedAt), written by the handler
//     onto the pod it promoted;
//   - the structural rule: the init script grants the master config to ordinal 0 or
//     to the pod the replica ConfigMap names, so a labeled master with ordinal > 0
//     that the ConfigMap does not name cannot have elected itself;
//   - the recorded pod's own answer: the pod the annotation names reports a role
//     other than master, so it has already given up whatever dataset it held.
//
// No row may REQUIRE a stamp to reach a safe outcome: during an operator upgrade old
// sidecars keep running and write none. The structural rule alone cannot carry that
// window either -- it can never exonerate pod-0, and pod-0 is exactly the pod a drain
// promotes, since the sidecar walks the ordinals ascending -- so the recorded pod's
// answer carries every cluster whose master is not pod-0, which after one adoption is
// all of them.
//
// The creation order is a fourth signal and it appears on the demotion side only. It
// may refuse, never adopt, and it expires: see recreatedAfter and the two tests that
// bracket its freshness window.

// masterLabeledPod builds a ready pod carrying the full label set the -rw Service
// selects on, i.e. what the sidecar leaves behind after labeling a pod.
func masterLabeledPod(v *vkov1.Valkey, ordinal int, role string) *corev1.Pod {
	name := fmt.Sprintf("%s-%d", v.Name, ordinal)
	pod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: v.Namespace,
			Labels:    common.PodLabels(v, common.ComponentValkey, name, role, nil),
		},
		Status: corev1.PodStatus{
			Phase:      corev1.PodRunning,
			Conditions: []corev1.PodCondition{{Type: corev1.PodReady, Status: corev1.ConditionTrue}},
		},
	}
	ownedByTestSts(v, common.ComponentValkey, pod)
	return pod
}

// drainStamped adds what internal/sidecar/drain.go stamps onto the pod it promoted
// on SIGTERM.
func drainStamped(pod *corev1.Pod) *corev1.Pod {
	return stampedAt(pod, time.Now().UTC().Format(time.RFC3339))
}

// createdAt back-dates a pod by age. Creation order decides whether a demotion is
// refused, so a fixture that leaves it at zero pins nothing: zero ties with zero, the
// rule stays inert, and the test passes for a reason no cluster ever has. Every
// fixture that reaches refuseDemotion therefore carries realistic ages.
func createdAt(pod *corev1.Pod, age time.Duration) *corev1.Pod {
	pod.CreationTimestamp = metav1.NewTime(time.Now().Add(-age).Truncate(time.Second))
	return pod
}

func stampedAt(pod *corev1.Pod, stamp string) *corev1.Pod {
	if pod.Annotations == nil {
		pod.Annotations = map[string]string{}
	}
	pod.Annotations[common.AnnotationDrainPromotedAt] = stamp
	return pod
}

// replicaConfigMapNaming builds the live replica ConfigMap the operator publishes
// when the known master is the given ordinal -- generated by the builder, so the
// parse under test runs against the real file content the init script reads.
func replicaConfigMapNaming(v *vkov1.Valkey, masterOrdinal int) *corev1.ConfigMap {
	published := v.DeepCopy()
	published.Annotations = map[string]string{
		builder.AnnotationKnownMaster: podHost(v.Name, masterOrdinal),
	}
	cm := builder.BuildReplicaConfigMap(published)
	controllerRefTo(v, cm)
	return cm
}

// splitBrainFixture builds the post-failover shape: a 2-replica non-Sentinel CR
// whose known-master annotation names pod-1, with both pods labeled master.
//
// The ages are the ordinary history of a long-running cluster: both pods were
// rescheduled at some point, pod-1 more recently than pod-0. That order is permanent
// once it exists, so it is exactly the input the creation-order refusal must NOT
// react to weeks later -- and with both timestamps left at zero no test in this file
// would have noticed that it did.
func splitBrainFixture() (*vkov1.Valkey, []client.Object) {
	v := newTestValkey("test", testNamespace, func(v *vkov1.Valkey) {
		v.Spec.Replicas = 2
		v.Annotations = map[string]string{
			builder.AnnotationKnownMaster: podHost("test", 1),
		}
	})
	return v, withDataStatefulSet([]client.Object{
		v,
		createdAt(masterLabeledPod(v, 0, common.RoleMaster), 12*24*time.Hour),
		createdAt(masterLabeledPod(v, 1, common.RoleMaster), 9*24*time.Hour),
	})
}

